STANDARD_CYCLES = ("udds", "hwfet", "us06", "nedc", "ece15", "eudc")


# ── Simulation ─────────────────────────────────────────────────────────
def bench_cycles(names=STANDARD_CYCLES, dt_sim_s: float = 0.25) -> list[dict]:
    """One run per cycle: speed, energy results, and how well the energy account closes."""
    rows = []
    for name in names:
        t0 = time.perf_counter()
        run = EVSimulator(EVConfig(dt_sim_s=dt_sim_s)).run(name)
        wall = time.perf_counter() - t0
        m, res = run.metrics(), run.ledger.relative_residuals()
        rows.append({
            "cycle": name, "duration_s": m["duration_s"], "distance_km": m["distance_km"], "wall_s": wall,
            "steps": run.n_steps, "realtime_factor": m["duration_s"] / wall,
            "Wh_per_km": m["consumption_Wh_per_km"], "regen_pct": 100.0 * m["regen_share_of_traction"],
            "drivetrain_eff": m["drivetrain_efficiency"], "soc_used_pct": m["soc_used_pct"],
            "peak_C": m["peak_discharge_C"], "peak_kW": m["peak_power_kW"], "max_T_C": m["max_temperature_C"],
            "trace_rms_kmh": m["trace_rms_error_kmh"],
            "closure_vehicle": res["vehicle"], "closure_pack": res["pack"], "closure_ocv": res["spline"]})
    return rows


def bench_step_convergence(cycle: str = "ece15", dts=(1.0, 0.5, 0.25, 0.125, 0.0625)) -> list[dict]:
    """The same drive at shrinking internal steps: results should settle, and the pack residual should fall."""
    rows = []
    for dt in dts:
        t0 = time.perf_counter()
        run = EVSimulator(EVConfig(dt_sim_s=dt)).run(cycle)
        rows.append({"dt_s": dt, "Wh_per_km": run.metrics()["consumption_Wh_per_km"],
                     "pack_residual_Wh": abs(run.ledger.pack_residual),
                     "closure_vehicle": run.ledger.relative_residuals()["vehicle"],
                     "wall_s": time.perf_counter() - t0})
    ref = rows[-1]["Wh_per_km"]
    for r in rows:
        r["vs_finest_pct"] = 100.0 * (r["Wh_per_km"] / ref - 1.0)
    return rows


def bench_legacy_agreement(names=("udds", "hwfet", "us06", "ece15", "urban_stop_go")) -> list[dict]:
    """The forward model against the repository's older inverse model (``simulate_drive``)."""
    rows = []
    for name in names:
        cfg = EVConfig()
        cyc = get_cycle(name)
        old = simulate_drive(cyc.speed_mps, 1.0, cfg.vehicle, PackModel())
        run = EVSimulator(cfg).run(cyc)
        net = float(np.sum(run["p_dc_inverter_W"][1:]) * run.dt_s / 3600.0)
        rows.append({"cycle": name, "legacy_Wh": old.net_energy_Wh, "forward_Wh": net,
                     "difference_pct": 100.0 * (net / old.net_energy_Wh - 1.0)})
    return rows


def _scenario_row(label: str, cycle: str, cfg: EVConfig) -> dict:
    run = EVSimulator(cfg).run(cycle)
    m = run.metrics()
    flags = sorted({n for f in run["limit_flags"] for n in describe_flags(int(f))})
    return {"scenario": label, "Wh_per_km": m["consumption_Wh_per_km"], "soc_used_pct": m["soc_used_pct"],
            "peak_kW": m["peak_power_kW"], "trace_rms_kmh": m["trace_rms_error_kmh"],
            "within_tol_pct": m["trace_within_tolerance_pct"], "limited_pct": m["time_power_limited_pct"],
            "flags": ", ".join(flags) or "none"}


def bench_conditions(cycle: str = "udds") -> list[dict]:
    """How consumption responds to vehicle and climate parameters (sensitivity, not validation)."""
    base = EVConfig()
    v = base.vehicle
    none = AuxiliaryLoads(base_W=0.0, hvac_cooling_W_per_K=0.0, hvac_heating_W_per_K=0.0)
    cases = [("baseline", base), ("mass 1300 kg", replace(base, vehicle=replace(v, mass_kg=1300.0))),
             ("mass 1900 kg", replace(base, vehicle=replace(v, mass_kg=1900.0))),
             ("drag coefficient 0.24", replace(base, vehicle=replace(v, drag_coefficient=0.24))),
             ("drag coefficient 0.40", replace(base, vehicle=replace(v, drag_coefficient=0.40))),
             ("no auxiliary loads", replace(base, aux=none)),
             ("ambient -10 °C", replace(base, ambient_C=-10.0)), ("ambient 38 °C", replace(base, ambient_C=38.0)),
             ("start at 50 % SOC", replace(base, soc0=0.5))]
    return [_scenario_row(label, cycle, cfg) for label, cfg in cases]


def bench_limits(cycle: str = "us06") -> list[dict]:
    """What happens when the pack cannot deliver: the car falls behind the trace and says why."""
    base = EVConfig()
    cases = [("baseline, default limits", base),
             ("pack power cap 60 kW", replace(base, limits=PackLimits(max_discharge_power_W=60_000.0))),
             ("pack power cap 40 kW", replace(base, limits=PackLimits(max_discharge_power_W=40_000.0))),
             ("pack power cap 25 kW", replace(base, limits=PackLimits(max_discharge_power_W=25_000.0))),
             ("pack current cap 0.5 C", replace(base, limits=PackLimits(max_discharge_C=0.5))),
             ("cold pack, -15 °C", replace(base, ambient_C=-15.0)),
             ("nearly empty, 5 % SOC", replace(base, soc0=0.05))]
    return [_scenario_row(label, cycle, cfg) for label, cfg in cases]


# ── Reproducibility ────────────────────────────────────────────────────
def _frame_digest(run) -> str:
    pub = EVCanPublisher(None)                      # builds frames only; no transport is used
    h = hashlib.sha256()
    for i in run.sample_indices():
        for f in pub.frames_for(run, int(i)):
            h.update(f.arbitration_id.to_bytes(2, "big") + f.data)
    return h.hexdigest()


def bench_reproducibility(cycle: str = "urban_stop_go") -> dict:
    cfg = EVConfig(dt_sim_s=0.5)
    a, b = EVSimulator(cfg).run(cycle), EVSimulator(cfg).run(cycle)
    code = f"import bms;print(bms.EVSimulator(bms.EVConfig(dt_sim_s=0.5)).run({cycle!r}).digest())"
    fresh = subprocess.run([sys.executable, "-c", code], cwd=ROOT, capture_output=True, text=True, timeout=300)
    seeded = EVSimulator(replace(cfg, seed=1)).run(cycle)
    return {"cycle": cycle, "digest": a.digest()[:16],
            "same_process_identical": a.digest() == b.digest(),
            "fresh_interpreter_identical": fresh.returncode == 0 and fresh.stdout.strip() == a.digest(),
            "can_frames_identical": _frame_digest(a) == _frame_digest(b),
            "telemetry_identical": a.telemetry(1.0) == b.telemetry(1.0),
            "manifest_identical": a.manifest() == b.manifest(),
            "different_seed_differs": seeded.digest() != a.digest()}


# ── CAN ────────────────────────────────────────────────────────────────
def bench_can(cycle: str = "udds") -> dict:
    run = EVSimulator(EVConfig()).run(cycle)
    received: list = []
    channel = f"bench-{uuid.uuid4().hex[:8]}"
    with VirtualCanTransport(channel) as tx, VirtualCanTransport(channel) as rx:
        stats = EVCanPublisher(tx).publish_run(
            run, after_sample=lambda i, frames: received.extend(rx.recv(timeout=1.0) for _ in frames))
    report = verify_against_telemetry(run, received, db=load_dbc(ROOT / "bms.dbc"))
    return {"cycle": cycle, "samples": stats.samples, "frames": stats.frames, "received": len(received),
            "wall_s": stats.wall_s, "frames_per_s": stats.frames / stats.wall_s, "decode_ok": report.ok,
            "missing": report.missing, "max_error": report.max_abs_error, "tolerance": report.tolerance,
            "sop_saturated_samples": stats.sop_saturated_samples}


# ── Gateway ────────────────────────────────────────────────────────────
def _record(i: int) -> TelemetryRecord:
    return TelemetryRecord(seq=i, t_s=float(i), timestamp=format_timestamp(DEFAULT_EPOCH_UNIX_S + i),
                           speed_mps=10.0 + i % 7, soc=0.9, voltage_V=350.0, current_A=12.0,
                           temperature_C=25.0, power_W=4200.0)


def _start_gateway(capacity: int):
    hub = TelemetryHub(capacity=capacity)
    authority = TokenAuthority(generate_secret())
    app = create_gateway_app(hub, authority, GatewayConfig(heartbeat_s=1.0))
    return hub, authority, GatewayServer(app).start()


def _wait_connected(clients, timeout_s: float = 20.0) -> None:
    deadline = time.monotonic() + timeout_s
    while not all(c.stats.connects >= 1 for c in clients):
        if time.monotonic() > deadline:
            raise RuntimeError("clients did not connect in time")
        time.sleep(0.005)


def bench_gateway_throughput(n_records: int, n_clients: int) -> dict:
    """Records per second from ``publish`` to every client, over loopback HTTP."""
    hub, authority, server = _start_gateway(n_records + 16)
    try:
        clients = [TelemetryClient(server.url, authority.issue(f"bench{i}")) for i in range(n_clients)]
        counts, done = [0] * n_clients, [0.0] * n_clients

        def consume(i):
            for _ in clients[i].stream():
                counts[i] += 1
            done[i] = time.perf_counter()
        threads = [threading.Thread(target=consume, args=(i,), daemon=True) for i in range(n_clients)]
        for t in threads:
            t.start()
        _wait_connected(clients)
        t0 = time.perf_counter()
        for i in range(n_records):
            hub.publish(_record(i))
        hub.close()
        for t in threads:
            t.join(120)
        elapsed = max(done) - t0
        return {"records": n_records, "clients": n_clients, "elapsed_s": elapsed,
                "per_client_records_per_s": n_records / elapsed,
                "aggregate_records_per_s": n_records * n_clients / elapsed,
                "all_received": all(c == n_records for c in counts)}
    finally:
        hub.close()
        server.stop()


def bench_gateway_latency(rate_hz: float, seconds: float) -> dict:
    """Time from ``publish`` to the client receiving the record, at a steady rate."""
    n = int(rate_hz * seconds)
    hub, authority, server = _start_gateway(n + 16)
    try:
        client = TelemetryClient(server.url, authority.issue("bench"))
        sent: dict[int, float] = {}
        latencies: list[float] = []

        def consume():
            for rec in client.stream():
                latencies.append((time.perf_counter() - sent[rec.seq]) * 1000.0)
        th = threading.Thread(target=consume, daemon=True)
        th.start()
        _wait_connected([client])
        start = time.perf_counter()
        for i in range(n):
            due = start + i / rate_hz
            while (now := time.perf_counter()) < due:
                time.sleep(min(0.001, due - now))
            sent[i] = time.perf_counter()
            hub.publish(_record(i))
        hub.close()
        th.join(60)
        lat = np.array(latencies)
        return {"rate_hz": rate_hz, "records": n, "received": int(lat.size), "p50_ms": float(np.percentile(lat, 50)),
                "p95_ms": float(np.percentile(lat, 95)), "p99_ms": float(np.percentile(lat, 99)),
                "max_ms": float(lat.max())}
    finally:
        hub.close()
        server.stop()


def bench_gateway_replay(n_records: int) -> dict:
    """A client that connects late and catches up from the ring buffer."""
    hub, authority, server = _start_gateway(n_records + 16)
    try:
        for i in range(n_records):
            hub.publish(_record(i))
        hub.close()
        client = TelemetryClient(server.url, authority.issue("bench"))
        t0 = time.perf_counter()
        count = sum(1 for _ in client.stream())
        elapsed = time.perf_counter() - t0
        return {"records": n_records, "received": count, "elapsed_ms": elapsed * 1000.0,
                "records_per_s": count / elapsed}
    finally:
        server.stop()


def bench_auth(n: int) -> dict:
    authority = TokenAuthority(generate_secret())
    t0 = time.perf_counter()
    tokens = [authority.issue("bench") for _ in range(n)]
    issue_s = time.perf_counter() - t0
    token = tokens[0]
    t0 = time.perf_counter()
    for _ in range(n):
        authority.verify(token)
    verify_s = time.perf_counter() - t0
    return {"iterations": n, "issue_per_s": n / issue_s, "verify_per_s": n / verify_s, "token_chars": len(token),
            "record_json_bytes": len(_record(0).to_json())}


# ── Driver ─────────────────────────────────────────────────────────────
def environment() -> dict:
    import scipy
    return {"bms": bms.__version__, "python": platform.python_version(), "platform": platform.platform(),
            "cpus": __import__("os").cpu_count(), "numpy": np.__version__, "scipy": scipy.__version__}


def run_all(quick: bool = False) -> dict:
    cycles = ("ece15",) if quick else STANDARD_CYCLES
    return {
        "environment": environment(),
        "cycles": bench_cycles(cycles),
        "convergence": bench_step_convergence("ece15", (1.0, 0.5, 0.25) if quick else (1.0, 0.5, 0.25, 0.125, 0.0625)),
        "legacy": bench_legacy_agreement(("ece15",) if quick else ("udds", "hwfet", "us06", "ece15", "urban_stop_go")),
        "conditions": [] if quick else bench_conditions(),
        "limits": [] if quick else bench_limits(),
        "reproducibility": bench_reproducibility(),
        "can": bench_can("ece15" if quick else "udds"),
        "gateway_throughput": [bench_gateway_throughput(300 if quick else 5000, 1)]
        + ([] if quick else [bench_gateway_throughput(5000, 4)]),
        "gateway_latency": bench_gateway_latency(100.0, 1.0 if quick else 5.0),
        "gateway_replay": bench_gateway_replay(500 if quick else 5000),
        "auth": bench_auth(2000 if quick else 20000),
    }


# ── Report ─────────────────────────────────────────────────────────────
def _table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _sci(x: float) -> str:
    return f"{x:.1e}"


