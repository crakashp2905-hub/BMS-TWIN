    ap.add_argument("--quick", action="store_true", help="a small, fast run (used by the test suite)")
    ap.add_argument("--write", metavar="PATH", help="write the Markdown report to PATH")
    args = ap.parse_args(argv)
    report = render_markdown(run_all(quick=args.quick))
    if args.write:
        Path(args.write).write_text(report, encoding="utf-8")
        print(f"wrote {args.write}")
